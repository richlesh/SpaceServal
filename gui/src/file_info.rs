/// A browser URL for an authoritative reference about the entry: fileinfo's
/// extension page for a known file extension, else a web search for the name.
pub fn online_lookup_url(path: &Path, is_dir: bool) -> String {
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    if is_dir {
        return format!(
            "https://duckduckgo.com/?q={}",
            encode(&format!("{name} folder"))
        );
    }
    match path.extension().and_then(|e| e.to_str()) {
        Some(ext) if !ext.is_empty() => {
            format!(
                "https://fileinfo.com/extension/{}",
                encode(&ext.to_ascii_lowercase())
            )
        }
        _ => format!(
            "https://duckduckgo.com/?q={}",
            encode(&format!("{name} file"))
        ),
    }
}

/// Minimal percent-encoding for a URL query component.
fn encode(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for b in s.bytes() {
        match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(b as char)
            }
            b' ' => out.push('+'),
            _ => out.push_str(&format!("%{b:02X}")),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn known_extension_is_described() {
        let e = describe(Path::new("/x/photo.PNG"), false);
        assert_eq!(e.name, "photo.PNG");
        assert_eq!(e.format, "PNG image");
        assert!(e.purpose.to_lowercase().contains("image"));
        assert!(!e.safe_to_delete.is_empty());
        assert_eq!(e.online_url, "https://fileinfo.com/extension/png");
    }

    #[test]
    fn directories_are_described_by_name() {
        let git = describe(Path::new("/proj/.git"), true);
        assert!(git.format.contains("Git"));
        assert!(git.safe_to_delete.to_uppercase().contains("NOT SAFE"));

        let generic = describe(Path::new("/proj/assets"), true);
        assert_eq!(generic.format, "Folder");
    }

    #[test]
    fn unknown_extension_falls_back() {
        let e = describe(Path::new("/x/weird.zzz"), false);
        assert_eq!(e.format, "File");
        assert_eq!(e.online_url, "https://fileinfo.com/extension/zzz");
    }

    #[test]
    fn no_extension_file() {
        let e = describe(Path::new("/x/README"), false);
        assert!(e.format.contains("no extension"));
        assert_eq!(e.online_url, "https://duckduckgo.com/?q=README+file");
    }
}
