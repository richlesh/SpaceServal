//! A small, offline knowledge base that explains what a file or directory is.
//!
//! Given a path, [`describe`] returns a human-readable [`FileExplanation`]
//! (format, what it's used for, and whether it's generally safe to delete). It
//! recognizes common file extensions and a handful of well-known special
//! names/directories. For anything it doesn't know, it still returns a generic
//! description plus an [`online_lookup_url`] the UI can offer so the user can
//! read an authoritative reference in their browser.
//!
//! The "safe to delete" guidance is deliberately conservative: it describes the
//! *typical* case and always reminds the user that deletion here is permanent.

use std::path::Path;

/// An explanation of a single file or directory, shown in the UI.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FileExplanation {
    /// The entry's basename.
    pub name: String,
    /// Short format name, e.g. "PNG image" or "Folder".
    pub format: String,
    /// What the file/format is used for.
    pub purpose: String,
    /// Conservative guidance on whether removing it is typically safe.
    pub safe_to_delete: String,
    /// A browser URL for an authoritative reference (extension lookup or a
    /// web search), always provided as a fallback / "learn more".
    pub online_url: String,
}

/// Describe the file or directory at `path`. `is_dir` tells directories apart
/// from files (callers already know this from the scan).
pub fn describe(path: &Path, is_dir: bool) -> FileExplanation {
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| path.to_string_lossy().into_owned());
    let online_url = online_lookup_url(path, is_dir);

    if is_dir {
        let (format, purpose, safe) = describe_dir(&name);
        return FileExplanation {
            name,
            format: format.to_string(),
            purpose: purpose.to_string(),
            safe_to_delete: safe.to_string(),
            online_url,
        };
    }

    let ext = path
        .extension()
        .and_then(|e| e.to_str())
        .map(|e| e.to_ascii_lowercase());

    let (format, purpose, safe) = match ext.as_deref() {
        Some(e) => describe_ext(e),
        None => (
            "File (no extension)",
            "A file with no extension; its type can't be inferred from the name alone.",
            "Unknown — inspect the file before deleting.",
        ),
    };

    FileExplanation {
        name,
        format: format.to_string(),
        purpose: purpose.to_string(),
        safe_to_delete: safe.to_string(),
        online_url,
    }
}

/// Guidance for a directory, keyed on a few well-known names.
